"""Disposable Docker liveness/auth smoke. Does not call or seed Supabase."""
import json
import secrets
import subprocess
import sys
import time
from urllib.error import HTTPError, URLError
from urllib.request import urlopen


def main():
    kind=sys.argv[1]
    assert kind in ('api','web')
    name='flamee-ci-'+kind+'-'+secrets.token_hex(4)
    port=18000 if kind=='api' else 18080
    inside=8000 if kind=='api' else 8080
    command=['docker','run','--detach','--rm','--name',name,'-p',f'127.0.0.1:{port}:{inside}']
    if kind=='api':
        environment={'FLAMEE_DEBUG':'false','FLAMEE_SECRET_KEY':secrets.token_urlsafe(40),
            'FLAMEE_SUPABASE_URL':'https://ci-not-a-project.supabase.invalid',
            'FLAMEE_SUPABASE_SERVICE_KEY':'ci-only-not-a-real-key','FLAMEE_CORS_ORIGINS':'["https://example.invalid"]'}
        for key,value in environment.items():command+=['-e',key+'='+value]
    command+=['flamee-'+kind+':ci']
    started=subprocess.run(command,capture_output=True)
    assert started.returncode==0,'Disposable CI container did not start'
    try:
        health='/health' if kind=='api' else '/healthz'
        deadline=time.monotonic()+90
        while True:
            try:
                with urlopen(f'http://127.0.0.1:{port}'+health,timeout=3) as response:
                    assert response.status==200
                    break
            except (URLError,OSError):
                assert time.monotonic()<deadline,'Container failed liveness check'
                time.sleep(1)
        if kind=='api':
            try:
                urlopen(f'http://127.0.0.1:{port}/api/v1/auth/me',timeout=10)
                raise AssertionError('Protected API accepted an unauthenticated request')
            except HTTPError as error:assert error.code==401
        else:
            with urlopen(f'http://127.0.0.1:{port}/moments',timeout=10) as response:
                assert response.status==200 and b'<html' in response.read().lower()
        user=subprocess.check_output(['docker','inspect',name,'--format','{{.Config.User}}'],text=True).strip()
        assert user and user not in ('0','root'),'Runtime must be non-root'
        print(json.dumps({'container':kind,'liveness':True,'auth_or_deep_link':True,'non_root':True}))
    finally:
        # Only the disposable container generated by this process is stopped.
        subprocess.run(['docker','stop',name],check=False,stdout=subprocess.DEVNULL)


if __name__=='__main__':main()
