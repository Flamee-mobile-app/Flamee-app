import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import test from "node:test";

test("conversation migration executes on isolated PostgreSQL and enforces authorization, retries and event ownership", async () => {
  const { PGlite } = await import("../../.local-tools/conversation-pg-test/node_modules/@electric-sql/pglite/dist/index.js");
  const db = new PGlite();
  try {
    await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role BYPASSRLS;
      CREATE TABLE users(id TEXT PRIMARY KEY,couple_id TEXT,full_name TEXT NOT NULL,username TEXT);
      CREATE TABLE couples(id TEXT PRIMARY KEY,partner1_id TEXT,partner2_id TEXT,status TEXT);
      CREATE TABLE memories(id TEXT PRIMARY KEY,couple_id TEXT);
      INSERT INTO users VALUES('alice','pair','Alice',NULL),('bob','pair','Bob',NULL),('charlie','other','Charlie',NULL),('dave','other','Dave',NULL);
      INSERT INTO couples VALUES('pair','alice','bob','active'),('other','charlie','dave','active');
      INSERT INTO memories VALUES('memory','pair'),('foreign','other');
      GRANT ALL ON users,couples,memories TO service_role;`);
    await db.exec(await readFile(new URL("../migrations/20261115_memory_conversation.sql", import.meta.url), "utf8"));
    await db.exec('SET ROLE service_role');
    const op = async (actor, action, memory = null, target = null, key = null, payload = {}) => (await db.query("SELECT memory_conversation_operation($1,$2,$3,$4,$5,$6::jsonb) AS result", [actor, action, memory, target, key, JSON.stringify(payload)])).rows[0].result;
    const created = await op('alice','create','memory',null,'a',{body:'Hello',parent_id:null});
    assert.equal(created.outcome,'ok'); const id = created.data.id;
    assert.equal((await op('alice','create','memory',null,'a',{body:'Hello',parent_id:null})).data.id,id);
    assert.equal((await op('alice','create','memory',null,'a',{body:'Changed'})).outcome,'conflict');
    assert.equal((await op('bob','inbox')).data.unread_count,1);
    assert.equal((await op('alice','inbox')).data.unread_count,0);
    assert.equal((await op('charlie','list','memory')).outcome,'not_found');
    assert.equal((await op('charlie','heart','memory',id)).outcome,'not_found');
    assert.equal((await op('bob','edit','memory',id,null,{body:'No',version:0})).outcome,'forbidden');
    const reply = await op('bob','create','memory',null,'b',{body:'Reply',parent_id:id});
    assert.equal(reply.outcome,'ok');
    assert.equal((await op('alice','create','memory',null,'nested',{body:'Nested',parent_id:reply.data.id})).outcome,'not_found');
    assert.equal((await op('alice','create','foreign',null,'wrong',{body:'No'})).outcome,'not_found');
    assert.equal((await op('bob','heart','memory',id)).data.heart_count,1);
    assert.equal((await op('bob','heart','memory',id)).data.heart_count,1);
    assert.equal((await op('alice','inbox')).data.unread_count,2);
    assert.equal((await op('bob','unheart','memory',id)).data.heart_count,0);
    assert.equal((await op('alice','inbox')).data.unread_count,1);
    await op('alice','heart','memory',id);
    assert.equal((await op('alice','inbox')).data.unread_count,1,'no self notification');
    assert.equal((await op('alice','edit','memory',id,null,{body:'Edited',version:0})).data.version,1);
    assert.equal((await op('alice','edit','memory',id,null,{body:'Stale',version:0})).outcome,'conflict');
    const notice = (await op('bob','inbox')).data.items[0];
    assert.equal((await op('alice','read',null,notice.id)).outcome,'not_found');
    assert.equal((await op('bob','read',null,notice.id)).data.unread_count,0);
    const removed = await op('alice','delete','memory',id,null,{version:1});
    assert.equal(removed.data.deleted,true); assert.equal(removed.data.body,'');
    assert.equal((await op('bob','list','memory')).data.total,2,'parent tombstone preserves reply');
    assert.equal((await op('bob','list','memory')).data.comment_count,1);
    assert.equal((await db.query("SELECT comment_count FROM memories WHERE id='memory'")).rows[0].comment_count,1);
    await db.exec("DELETE FROM memories WHERE id='memory'");
    const inbox = (await op('alice','inbox')).data;
    assert.equal(inbox.items[0].available,false);
    assert.equal(inbox.items[0].memory_id,null);
    await db.exec("UPDATE couples SET status='dissolved' WHERE id='pair'");
    assert.equal((await op('alice','inbox')).outcome,'forbidden');
    const grants = await db.query("SELECT has_table_privilege('authenticated','memory_comments','SELECT') AS direct, has_function_privilege('authenticated','memory_conversation_operation(text,text,text,text,text,jsonb)','EXECUTE') AS rpc");
    assert.equal(grants.rows[0].direct,false); assert.equal(grants.rows[0].rpc,false);
    await db.exec('SET ROLE authenticated');
    await assert.rejects(db.query('SELECT * FROM memory_comments'), (error) => error.code === '42501');
    await assert.rejects(db.query("SELECT memory_conversation_operation('alice','inbox')"), (error) => error.code === '42501');
  } finally { await db.close(); }
});
